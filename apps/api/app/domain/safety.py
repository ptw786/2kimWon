# 바로 뒤에 분명한 부정이 오면 건너뛴다: "숨 차는 건 없어", "가슴 아픈 데는 없어요", "넘어진 적은 없어"
# ("넘어질 뻔했는데 괜찮아"처럼 일이 있었다는 말은 걸러내지 않는다 — 위 원칙 그대로)
_DENIED = re.compile(r'^.{0,3}(건|거|게|데|적|곳|일)(은|는|이|가|도)?(전혀|하나도|별로|아직)?(없|안)|^.{0,2}지(는|도)?않')


def _first(rx, c: str):
    for m in rx.finditer(c):
        if not _DENIED.search(c[m.end():m.end() + 10]):
            return m
    return None


def detect(text: str) -> list[dict]:
    """[{category, quote}] — 분류마다 최대 1개. quote 는 원문 구절 그대로."""
    if not text:
        return []
    c, index = compact(text)
    found = {}
    for cat, rx in _COMPILED:
        m = _first(rx, c)
        if m:
            found[cat] = {'category': cat, 'quote': clause_at(text, index[m.start()])}
    for cat, a, b in _COMBOS:
        m = _first(a, c)
        if cat not in found and m and b.search(c[:m.start()] + c[m.end():]):
            found[cat] = {'category': cat, 'quote': clause_at(text, index[m.start()])}
    order = [cat for cat, _ in CATEGORIES]
    return sorted(found.values(), key=lambda f: order.index(f['category']))
